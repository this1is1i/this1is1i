CREATE TABLE IF NOT EXISTS audit_event (
    journal_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    idempotency_key VARCHAR(400) PRIMARY KEY,
    task_id VARCHAR(100) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    payload CLOB NOT NULL,
    result CLOB,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE
);

ALTER TABLE audit_event ADD COLUMN IF NOT EXISTS result CLOB;
-- JSON Schema maxLength counts Unicode code points; H2 VARCHAR counts UTF-16 units.
ALTER TABLE audit_event ALTER COLUMN idempotency_key VARCHAR(400);
ALTER TABLE audit_event ADD COLUMN IF NOT EXISTS journal_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS ux_audit_event_journal_sequence ON audit_event(journal_sequence);
ALTER TABLE audit_event ADD COLUMN IF NOT EXISTS plan_scope VARCHAR(64) NOT NULL DEFAULT '';

-- A single-node database is permanently bound to one configured plan.
CREATE TABLE IF NOT EXISTS project_plan (
    slot INTEGER PRIMARY KEY CHECK (slot = 1),
    fingerprint VARCHAR(64) NOT NULL,
    definition_json CLOB NOT NULL,
    architect VARCHAR(200),
    architect_at TIMESTAMP WITH TIME ZONE,
    manager VARCHAR(200),
    manager_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS project_revision (
    fingerprint VARCHAR(64) PRIMARY KEY,
    parent_fingerprint VARCHAR(64),
    definition_json CLOB NOT NULL,
    architect VARCHAR(200), architect_at TIMESTAMP WITH TIME ZONE,
    manager VARCHAR(200), manager_at TIMESTAMP WITH TIME ZONE,
    activated_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- The local Mock executor owns its job acknowledgement independently of the coordinator journal.
CREATE TABLE IF NOT EXISTS mock_executor_job (
    execution_id VARCHAR(100) PRIMARY KEY,
    request_hash VARCHAR(64) NOT NULL,
    result_json CLOB NOT NULL
);

-- Immutable evidence objects, scoped to an approved plan. No update/delete application API.
CREATE TABLE IF NOT EXISTS evidence_record (
    id VARCHAR(64) PRIMARY KEY,
    plan_scope VARCHAR(64) NOT NULL,
    operation_key VARCHAR(160) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    payload CLOB NOT NULL,
    UNIQUE (plan_scope, operation_key)
);
